export const T = {
  server: 'plugin_keycloak_server',
  realm: 'plugin_keycloak_realm',
  client: 'plugin_keycloak_client',
  redirectUrl: 'plugin_keycloak_redirect_url',
} as const;

// ============================================================================
// Column factory functions
// ============================================================================

/**
 * Create a standard text column.
 * `column` lets the logical API name differ from the physical DB column
 * (e.g. name `server_url` → column `url`, because the serializer already
 * emits a `url` field pointing at the object's API endpoint).
 */
function textCol(
  name: string,
  opts: {
    writable?: boolean;
    required?: boolean;
    maxLength?: number;
    column?: string;
    formHidden?: boolean;
  } = {},
): ColumnMeta {
  return {
    name,
    column: opts.column ?? name,
    tsKind: 'string',
    nullable: !opts.required,
    writable: opts.writable ?? true,
    required: opts.required ?? false,
    ...(opts.maxLength && { maxLength: opts.maxLength }),
    ...(opts.formHidden && { formHidden: true }),
  };
}

/**
 * Create a foreign key column.
 */
function fkCol(name: string, references: string, opts: { writable?: boolean } = {}): ColumnMeta {
  return {
    name,
    column: `${name}_id`,
    tsKind: 'number',
    nullable: false,
    writable: opts.writable ?? true,
    required: true,
    references,
  };
}

/**
 * Create a timestamp column (read-only, auto-managed).
 */
function timestampCol(name: string): ColumnMeta {
  return {
    name,
    column: name,
    tsKind: 'string',
    nullable: false,
    writable: false,
    required: false,
  };
}

// ============================================================================
// Table metadata
