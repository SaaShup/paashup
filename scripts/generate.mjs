#!/usr/bin/env node
// Generates src/model/types.ts and src/model/metadata.ts from datamodel/data-model.json.
// The persisted-column logic MUST match datamodel/build_schema.py so the generated
// TypeScript matches the SQL schema exactly.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const model = JSON.parse(readFileSync(join(ROOT, 'datamodel', 'data-model.json'), 'utf8'));
const ENTITIES = model.entities;

// Mirror of build_schema.py COMPUTED + TIMESTAMPS
const COMPUTED = new Set([
  'url',
  'display',
  'display_url',
  'id',
  '_depth',
  'family',
  'children',
  'depth',
  'device_count',
  'prefix_count',
  'vlan_count',
  'rack_count',
  'ipaddress_count',
  'virtualmachine_count',
  'allocated_vcpus',
  'allocated_memory',
  'allocated_disk',
  'cable_count',
  'tenant_count',
  'circuit_count',
  'site_count',
  'vrf_count',
  'cluster_count',
  'tagged_items',
  'permissions',
  'groups',
]);
const TIMESTAMPS = new Set(['created', 'last_updated']);

const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const tableOf = (e) => `${e.section}_${snake(e.model)}`;

function tsKind(f) {
  const { kind, type } = f;
  if (kind === 'json' || kind === 'embedded') return 'json';
  if (type.startsWith('json') || type.startsWith('array')) return 'json';
  if (type === 'boolean') return 'boolean';
  if (kind === 'fk' || kind === 'generic_id') return 'number';
  if (kind === 'enum') return f.enum.every((v) => typeof v === 'number') ? 'number' : 'string';
  if (['integer', 'bigint', 'number', 'decimal'].includes(type)) return 'number';
  return 'string'; // strings, datetime, date, uuid, content-type, generic_type
}

/** Columns we actually persist (mirror of build_schema.persisted_fields), plus id. */
function persistedColumns(ent) {
  const cols = [];
  for (const f of ent.fields) {
    if (f.kind === 'm2m') continue;
    if (COMPUTED.has(f.name)) continue;
    if (f.read_only && !TIMESTAMPS.has(f.name) && !f.auto) continue;
    const column = f.kind === 'fk' ? `${f.name}_id` : f.name;
    const writable = !!f.writable && !f.read_only && !TIMESTAMPS.has(f.name);
    const required = !!f.required_on_create && !f.nullable;
    const meta = {
      name: f.name,
      column,
      tsKind: tsKind(f),
      nullable: !!f.nullable,
      writable,
      required,
    };
    if (f.auto) meta.auto = f.auto;
    if (f.references) meta.references = f.references;
    if (f.kind === 'generic_type') meta.genericRel = f.name.replace(/_type$/, '');
    else if (f.kind === 'generic_id') meta.genericRel = f.name.replace(/_id$/, '');
    if (f.max_length) meta.maxLength = f.max_length;
    if (f.kind === 'enum') {
      meta.enum = f.enum;
      if (f.enum_labels) meta.enumLabels = f.enum_labels;
    }
    cols.push(meta);
  }
  return cols;
}

function tsType(col) {
  let base;
  if (col.enum) {
    base = col.enum
      .map((v) => (typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "\\'")}'`))
      .join(' | ');
  } else {
    base = { number: 'number', string: 'string', boolean: 'boolean', json: 'Json' }[col.tsKind];
  }
  return col.nullable ? `${base} | null` : base;
}

// ---- emit types.ts ----------------------------------------------------------
const tlines = [
  '// AUTO-GENERATED by scripts/generate.mjs from datamodel/data-model.json. Do not edit.',
  `// NetBox ${model.source} compatible.`,
  '',
  'export type Json = Record<string, unknown> | unknown[] | string | number | boolean | null;',
  '',
  '/** A many-to-many value in a write request: an id, or an object with id/name/slug. */',
  'export type RelationInput = (number | { id?: number; name?: string; slug?: string })[];',
  '',
];

for (const ent of Object.values(ENTITIES)) {
  const cols = persistedColumns(ent);
  const ro = ent.origin === 'core' && !ent.write_schema; // read-only endpoint
  tlines.push(`/** ${ent.model} — \`${ent.endpoint}\`${ro ? ' (read-only)' : ''} */`);
  tlines.push(`export interface ${ent.model} {`);
  tlines.push('  id: number;');
  for (const c of cols) {
    const opt = TIMESTAMPS.has(c.name) ? '?' : '';
    tlines.push(`  ${c.name}${opt}: ${tsType(c)};`);
  }
  tlines.push('}');
  // Create / Update input shapes (writable columns + M2M relations)
  const w = cols.filter((c) => c.writable);
  const relNames = ro ? [] : (ent.relations ?? []).map((r) => r.name);
  if (!ro && (w.length || relNames.length)) {
    tlines.push(`export interface ${ent.model}Create {`);
    for (const c of w) {
      const opt = c.required ? '' : '?';
      tlines.push(`  ${c.name}${opt}: ${tsType(c)};`);
    }
    for (const name of relNames) tlines.push(`  ${name}?: RelationInput;`);
    tlines.push('}');
    tlines.push(`export type ${ent.model}Update = Partial<${ent.model}Create>;`);
  }
  tlines.push('');
}

// Type map keyed by table name, so repository(db, 'dcim_device') is fully typed.
tlines.push('/** Maps each table name to its row / create / update types. */');
tlines.push('export interface TableTypeMap {');
for (const ent of Object.values(ENTITIES)) {
  const table = tableOf(ent);
  const ro = ent.origin === 'core' && !ent.write_schema;
  const hasWrite =
    !ro && (persistedColumns(ent).some((c) => c.writable) || (ent.relations ?? []).length > 0);
  const create = hasWrite ? `${ent.model}Create` : 'never';
  const update = hasWrite ? `${ent.model}Update` : 'never';
  tlines.push(
    `  ${JSON.stringify(table)}: { row: ${ent.model}; create: ${create}; update: ${update} };`,
  );
}
tlines.push('}');
tlines.push('');

// ---- emit metadata.ts -------------------------------------------------------
const mlines = [
  '// AUTO-GENERATED by scripts/generate.mjs from datamodel/data-model.json. Do not edit.',
  "import type { TableMeta } from './meta-types.js';",
  '',
  'export const tables = {',
];

for (const ent of Object.values(ENTITIES)) {
  const cols = persistedColumns(ent);
  const table = tableOf(ent);
  const ro = ent.origin === 'core' && !ent.write_schema;
  mlines.push(`  ${JSON.stringify(table)}: {`);
  mlines.push(`    model: ${JSON.stringify(ent.model)}, table: ${JSON.stringify(table)},`);
  mlines.push(
    `    section: ${JSON.stringify(ent.section)}, endpoint: ${JSON.stringify(ent.endpoint)},`,
  );
  mlines.push(`    origin: ${JSON.stringify(ent.origin)}, pk: 'id', readOnly: ${ro},`);
  mlines.push(`    objectType: ${JSON.stringify(ent.object_type)},`);
  const rels = (ent.relations ?? []).map((r) => {
    const parts = [
      `name: ${JSON.stringify(r.name)}`,
      `kind: ${JSON.stringify(r.kind)}`,
      `target: ${JSON.stringify(r.target)}`,
      `targetTable: ${JSON.stringify(r.target_table)}`,
    ];
    if (r.kind === 'm2m') {
      parts.push(`joinTable: ${JSON.stringify(r.join_table)}`);
      parts.push(`selfColumn: ${JSON.stringify(r.self_column)}`);
      parts.push(`targetColumn: ${JSON.stringify(r.target_column)}`);
    }
    return `{ ${parts.join(', ')} }`;
  });
  mlines.push(
    `    relations: [${rels.length ? '\n      ' + rels.join(',\n      ') + ',\n    ' : ''}],`,
  );
  const counts = (ent.counts ?? []).map(
    (c) =>
      `{ name: ${JSON.stringify(c.name)}, table: ${JSON.stringify(c.table)}, column: ${JSON.stringify(c.column)} }`,
  );
  mlines.push(
    `    counts: [${counts.length ? '\n      ' + counts.join(',\n      ') + ',\n    ' : ''}],`,
  );
  mlines.push('    columns: [');
  for (const c of cols) {
    const parts = [
      `name: ${JSON.stringify(c.name)}`,
      `column: ${JSON.stringify(c.column)}`,
      `tsKind: ${JSON.stringify(c.tsKind)}`,
      `nullable: ${c.nullable}`,
      `writable: ${c.writable}`,
      `required: ${c.required}`,
    ];
    if (c.references) parts.push(`references: ${JSON.stringify(c.references)}`);
    if (c.genericRel) parts.push(`genericRel: ${JSON.stringify(c.genericRel)}`);
    if (c.maxLength) parts.push(`maxLength: ${c.maxLength}`);
    if (c.enum) parts.push(`enum: ${JSON.stringify(c.enum)}`);
    if (c.enumLabels) parts.push(`enumLabels: ${JSON.stringify(c.enumLabels)}`);
    if (c.auto) parts.push(`auto: ${JSON.stringify(c.auto)}`);
    mlines.push(`      { ${parts.join(', ')} },`);
  }
  mlines.push('    ],');
  mlines.push('  },');
}
mlines.push('} satisfies Record<string, TableMeta>;');
mlines.push('');
mlines.push('export type TableName = keyof typeof tables;');
mlines.push('');

const outDir = join(ROOT, 'src', 'model');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'types.ts'), tlines.join('\n'));
writeFileSync(join(outDir, 'metadata.ts'), mlines.join('\n'));

const n = Object.keys(ENTITIES).length;
console.log(`Generated src/model/types.ts (${n} interfaces) and src/model/metadata.ts`);
