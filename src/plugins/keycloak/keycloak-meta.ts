const serverMeta: TableMeta = {
  model: 'KeycloakServer',
  table: T.server,
  section: 'plugins',
  endpoint: '/api/plugins/keycloak/servers/',
  origin: 'plugin',
  pk: 'id',
  objectType: 'plugins.keycloakserver',
  readOnly: false,
  relations: [],
  counts: [{ name: 'realm_count', table: T.realm, column: 'server_id' }],
  columns: [
    textCol('name', { required: true, maxLength: 255 }),
    // logical name differs from column: `url` would clash with the API url field
    textCol('server_url', { required: true, maxLength: 2048, column: 'url' }),
    textCol('admin_username', { required: true, maxLength: 255 }),
    textCol('admin_password', { required: true, maxLength: 1024 }),
    timestampCol('created_at'),
    timestampCol('updated_at'),
  ],
};

const realmMeta: TableMeta = {
  model: 'KeycloakRealm',
  table: T.realm,
  section: 'plugins',
  endpoint: '/api/plugins/keycloak/realms/',
  origin: 'plugin',
  pk: 'id',
  objectType: 'plugins.keycloakrealm',
  readOnly: false,
  relations: [],
  counts: [{ name: 'client_count', table: T.client, column: 'realm_id' }],
  columns: [
    fkCol('server', 'KeycloakServer'),
    // logical name `name` so the engine serializer can compute `display`
    textCol('name', { required: true, maxLength: 255, column: 'realm_name' }),
  ],
};

const clientMeta: TableMeta = {
  model: 'KeycloakClient',
  table: T.client,
  section: 'plugins',
  endpoint: '/api/plugins/keycloak/clients/',
  origin: 'plugin',
  pk: 'id',
  objectType: 'plugins.keycloakclient',
  readOnly: false,
  relations: [],
  counts: [{ name: 'redirect_url_count', table: T.redirectUrl, column: 'client_id' }],
  columns: [
    fkCol('realm', 'KeycloakRealm'),
    // logical name `name` (column `client_id`): the Keycloak clientId
    textCol('name', { required: true, maxLength: 255, column: 'client_id' }),
    // generated by Keycloak at creation; read-only here
    textCol('secret', { writable: false, maxLength: 512 }),
    // Keycloak's internal client id — kept for updates/deletes, not user-facing
    textCol('kc_uuid', { writable: false, maxLength: 64, formHidden: true }),
  ],
};

const redirectUrlMeta: TableMeta = {
  model: 'KeycloakRedirectUrl',
  table: T.redirectUrl,
  section: 'plugins',
  endpoint: '/api/plugins/keycloak/redirect-urls/',
  origin: 'plugin',
  pk: 'id',
  objectType: 'plugins.keycloakredirecturl',
  readOnly: false,
  relations: [],
  counts: [],
  columns: [
    fkCol('client', 'KeycloakClient'),
    // logical name `name` (column `url`): gives a proper `display` and avoids
    // clobbering the serializer's API `url` field. 750 matches the MariaDB
    // column (unique-key size limit).
    textCol('name', { required: true, maxLength: 750, column: 'url' }),
    // 'callback' (client redirectUris) or 'post_logout' (post-logout URIs)
    {
      name: 'kind',
      column: 'kind',
      tsKind: 'string',
      nullable: false,
      writable: true,
      required: false,
      enum: ['callback', 'post_logout'],
      enumLabels: { callback: 'Callback', post_logout: 'Post-logout' },
    },
    timestampCol('created_at'),
  ],
};

